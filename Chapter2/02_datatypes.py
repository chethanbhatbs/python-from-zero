a = 1 # a is an integer
b = 2.5 # b is a float
print(a+b) # This will print the sum of a and b, which is 3.5
c = "Hello, World!" # c is a string
print(c) # This will print the string stored in c
d = True # d is a boolean
print(d) # This will print the boolean value stored in d
e = None # e is a NoneType
print(e) # This will print None, which represents the absence of a value
a = -5 # a is now assigned a negative integer value
print(a) # This will print the new value of a, which is -5